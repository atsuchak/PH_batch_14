const friends = ["Alam", "Kalam", "Gelam", "Elam", "Balam"];

console.log(friends);

// push
friends.push("Boshlam");
friends.push("Khailam");
console.log(friends);

// pop
friends.pop();
friends.pop();
console.log(friends);

// shift
friends.shift();
friends.shift();
console.log(friends);

// unshift
friends.unshift("Accha");
console.log(friends);